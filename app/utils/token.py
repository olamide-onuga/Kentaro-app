import os
from itsdangerous import URLSafeTimedSerializer, BadSignature, SignatureExpired


def _get_serializer():
    secret_key = os.getenv('SECRET_KEY', 'dev-secret')
    return URLSafeTimedSerializer(secret_key)


def generate_confirmation_token(email: str, expires_sec: int = 86400) -> str:
    """Generate a token for email confirmation or password reset.
    The token expires after ``expires_sec`` seconds (default 24 h)."""
    s = _get_serializer()
    return s.dumps(email, salt='email-confirm')


def confirm_token(token: str, max_age: int = 86400) -> str:
    """Validate a token generated by ``generate_confirmation_token``.
    Returns the email address if valid, raises ``SignatureExpired`` or ``BadSignature`` otherwise."""
    s = _get_serializer()
    return s.loads(token, salt='email-confirm', max_age=max_age)
